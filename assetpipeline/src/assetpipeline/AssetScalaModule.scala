package assetpipeline

import mill.*

/** A Scala module which uses assets. The files of all [[assetModules]] are
  * added to its resources, so that they end up on the class path and in the
  * jar.
  */
trait AssetScalaModule extends AssetConsumerModule with mill.scalalib.ScalaModule:

  override def resources: T[Seq[PathRef]] = Task:
    super.resources() :+ allAssets()

  /** The package of the generated asset references. */
  def assetPackage: T[String] = "assets"

  /** Generates Scala source with one object per asset, holding one constant
    * per file with the path at which that file is stored in [[allAssets]]:
    *
    * ```scala
    * package assets
    *
    * object web:
    *   final val `css/app.css` = "/assets/web/<hash>/css/app.css"
    * ```
    */
  def assetReferences: T[PathRef] = Task:
    val base = os.SubPath(assetPath())
    val pkg = assetPackage()
    val out = new StringBuilder
    out ++= "// generated by mill-assetpipeline, do not edit\n"
    out ++= s"package ${pkg.split('.').map(AssetScalaModule.ident).mkString(".")}\n"
    for manifest <- allAssetManifests() do
      out ++= s"\nobject ${AssetScalaModule.ident(manifest.name)}:\n"
      for file <- manifest.files do
        val path = "/" + (base / manifest.name / manifest.sha256 / file.path).toString
        if file.path.toString.exists(c => c == '`' || c.isControl) then
          Task.fail(s"Asset file name cannot be used as a Scala identifier: ${file.path}")
        out ++= s"  final val `${file.path}` = ${AssetScalaModule.literal(path)}\n"
    os.write(Task.dest / pkg.split('.') / "assets.scala", out.result(), createFolders = true)
    PathRef(Task.dest)

  override def generatedSources: T[Seq[PathRef]] = Task:
    super.generatedSources() :+ assetReferences()

object AssetScalaModule:

  private val keywords = Set(
    "abstract", "case", "catch", "class", "def", "do", "else", "enum",
    "export", "extends", "false", "final", "finally", "for", "given", "if",
    "implicit", "import", "lazy", "match", "new", "null", "object",
    "override", "package", "private", "protected", "return", "sealed",
    "super", "then", "throw", "trait", "true", "try", "type", "val", "var",
    "while", "with", "yield"
  )

  /** `name` as a Scala identifier, in backticks only if needed. */
  private def ident(name: String): String =
    if name.matches("[A-Za-z_][A-Za-z0-9_]*") && !keywords(name) then name
    else s"`$name`"

  /** `s` as a Scala string literal. */
  private def literal(s: String): String =
    val b = new StringBuilder("\"")
    s.foreach:
      case '"' => b ++= "\\\""
      case '\\' => b ++= "\\\\"
      case c if c.isControl => b ++= f"\\u${c.toInt}%04x"
      case c => b += c
    b += '"'
    b.result()
